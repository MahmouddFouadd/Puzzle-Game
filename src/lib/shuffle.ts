/** Deterministic shuffle: the same seed always gives the same order, so an answer list does not jump
 *  around on reload, but the correct option is no longer always shown first. Display only: answers are
 *  still sent and graded by option id. */
function hash(s: string): number {
  let h = 2166136261
  for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619) }
  return h >>> 0
}
function rng(seed: number) {
  let a = seed
  return () => { a = (a + 0x6d2b79f5) | 0; let t = Math.imul(a ^ (a >>> 15), 1 | a); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296 }
}
export function seededShuffle<T>(items: readonly T[], seed: string): T[] {
  const out = [...items], next = rng(hash(seed))
  for (let i = out.length - 1; i > 0; i--) { const j = Math.floor(next() * (i + 1)); [out[i], out[j]] = [out[j], out[i]] }
  return out
}
