#!/usr/bin/env node
/**
 * Converts a Detective "case pack" JSON (cases/stages/scenes/evidence/suspects/statements/stages_questions/
 * relations/hints/timeline_events/solution) into an idempotent seed SQL file for Supabase.
 *
 *   node scripts/detective-pack-to-sql.mjs <pack.json> <slug-folder> [boxes.json] > supabase/seed/detective_<name>.sql
 *
 * - Images are expected at public/demo/detective/<slug-folder>/{cover,scene-N}.webp.
 * - Fixed UUIDs (v5 of the case slug + item key) and ON CONFLICT DO NOTHING make re-runs safe.
 * - The case is inserted as DRAFT; publish it with publish_detective_case() after review.
 * - Pack values the database does not support are mapped, never dropped:
 *     relation CHRONOLOGY -> TEMPORAL, REQUIRES_CONTEXT -> CONTEXTUAL;
 *     truth PARTIALLY_FALSE -> FALSE, UNSUPPORTED -> INCOMPLETE;
 *     EVENT_ORDERING -> multiple choice between orderings; FIND_EVIDENCE -> multiple choice between the scene's clues;
 *     other option-based types (INTERPRET_CLUE, COMBINE_CLUES, ...) -> MULTIPLE_CHOICE.
 * - Missing English text falls back to the Arabic text (the app is Arabic-first).
 */
import { createHash } from 'node:crypto'
import { existsSync, readFileSync } from 'node:fs'
import { normalizePack, validatePack } from './detective-pack-lib.mjs'

const [packPath, folder, boxesPath] = process.argv.slice(2)
if (!packPath || !folder) { console.error('usage: detective-pack-to-sql.mjs <pack.json> <slug-folder> [boxes.json]'); process.exit(2) }
const boxes = boxesPath ? JSON.parse(readFileSync(boxesPath, 'utf8')) : {}
const rawPack = JSON.parse(readFileSync(packPath, 'utf8'))
{
  const asset = (name) => existsSync(new URL(`../public/demo/detective/${folder}/${name}.webp`, import.meta.url))
  const { errors, warnings } = validatePack(rawPack, { boxes, assetExists: process.env.SKIP_ASSET_CHECK ? undefined : asset })
  for (const w of warnings) console.error(`warning: ${w}`)
  if (errors.length) { console.error(errors.map((e) => `error: ${e}`).join('\n')); process.exit(1) }
}
const pack = normalizePack(rawPack)
const C = pack.case
const slug = C.slug

// ---- helpers
const NS = Buffer.from('6f1c8a52b0e94d7e9a3f2c5d8e7b4a10', 'hex')
function uuid(name) {
  const h = createHash('sha1').update(NS).update(`${slug}:${name}`).digest()
  h[6] = (h[6] & 0x0f) | 0x50; h[8] = (h[8] & 0x3f) | 0x80
  const x = h.subarray(0, 16).toString('hex')
  return `${x.slice(0, 8)}-${x.slice(8, 12)}-${x.slice(12, 16)}-${x.slice(16, 20)}-${x.slice(20, 32)}`
}
const q = (v) => (v === null || v === undefined ? 'null' : String(v) === '' ? "''" : `$q$${String(v).replace(/\$q\$/g, '')}$q$`)
const j = (v) => `${q(JSON.stringify(v))}::jsonb`
const uarr = (ids) => (ids.length ? `array[${ids.map((i) => `'${i}'::uuid`).join(',')}]::uuid[]` : `'{}'::uuid[]`)
const en = (e, a) => (e && String(e).trim() ? e : a)
const fail = (m) => { throw new Error(`${slug}: ${m}`) }
const pick = (n, k) => { const h = createHash('sha1').update(`${slug}:${k}`).digest(); return h[0] % n }

const out = []
const line = (s) => out.push(s)

// ---- ids
const version = uuid('version:1')
const caseId = uuid('case')
const stageId = Object.fromEntries(pack.stages.map((s) => [s.stage_key, uuid(`stage:${s.stage_key}`)]))
const evidence = []
for (const sc of pack.scenes) for (const e of sc.evidence) evidence.push({ ...e, scenePos: sc.position })
const evId = Object.fromEntries(evidence.map((e) => [e.key, uuid(`evidence:${e.key}`)]))
const ev = (k, where) => evId[k] ?? fail(`unknown evidence "${k}" in ${where}`)
const suspectId = Object.fromEntries(pack.suspects.map((s) => [s.key, uuid(`suspect:${s.key}`)]))

const REL = { SUPPORTS: 'SUPPORTS', CONTRADICTS: 'CONTRADICTS', TEMPORAL: 'TEMPORAL', CONTEXTUAL: 'CONTEXTUAL', CHRONOLOGY: 'TEMPORAL', REQUIRES_CONTEXT: 'CONTEXTUAL' }
const TRUTH = { TRUE: 'TRUE', FALSE: 'FALSE', INCOMPLETE: 'INCOMPLETE', UNREVIEWED: 'UNREVIEWED', PARTIALLY_FALSE: 'FALSE', UNSUPPORTED: 'INCOMPLETE' }
const CLASS = new Set(['OBSERVATION', 'FACT', 'INFERENCE', 'PROBABILITY', 'ASSUMPTION'])

line(`-- Detective case: ${C.title} (${C.title_ar}). Art in public/demo/detective/${folder}.`)
line(`-- Generated by scripts/detective-pack-to-sql.mjs from a case pack. Idempotent: fixed UUIDs, ON CONFLICT DO NOTHING.`)
line(`-- Inserted as DRAFT; publish with publish_detective_case('${caseId}').`)
line(`do $$ declare v_user uuid; begin`)
line(`select ur.user_id into v_user from user_roles ur where ur.role::text = 'SUPER_ADMIN' order by ur.user_id limit 1;`)
line(`if v_user is null then raise exception 'needs a SUPER_ADMIN user'; end if;`)

const img = (name) => `demo/detective/${folder}/${name}.webp`
line(`insert into detective_cases(id, slug, title, title_ar, description, description_ar, case_type, difficulty, age_min, age_max, status, created_by, category, estimated_minutes, briefing, briefing_ar, objective, objective_ar, cover_image_path) values ('${caseId}', ${q(slug)}, ${q(C.title)}, ${q(C.title_ar)}, ${q(en(C.description, C.description_ar))}, ${q(C.description_ar)}, 'FULL', ${Number(C.difficulty) || 2}, ${C.age_min ?? 'null'}, ${C.age_max ?? 'null'}, 'DRAFT', v_user, ${q(C.category_ar || C.category || 'MYSTERY')}, ${Number(C.estimated_minutes) || 15}, ${q(en(C.briefing, C.briefing_ar))}, ${q(C.briefing_ar)}, ${q(en(C.objective, C.objective_ar))}, ${q(C.objective_ar)}, '${img('cover')}') on conflict (id) do nothing;`)
if (Object.keys(pack.settings).length) line(`update detective_cases set settings = ${j(pack.settings)} where id = '${caseId}';`)
line(`insert into detective_case_versions(id, case_id, version_number, status, created_by) values ('${version}', '${caseId}', 1, 'DRAFT', v_user) on conflict (id) do nothing;`)

for (const s of pack.stages) {
  const rule = s.unlock_rule?.requires_stage ? { requires_stage: s.unlock_rule.requires_stage } : {}
  line(`insert into detective_stages(id, version_id, stage_key, position, title, title_ar, unlock_rule) values ('${stageId[s.stage_key]}', '${version}', ${q(s.stage_key)}, ${s.position}, ${q(en(s.title, s.title_ar))}, ${q(s.title_ar)}, ${j(rule)}) on conflict (id) do nothing;`)
}

for (const sc of pack.scenes) {
  const sid = uuid(`scene:${sc.position}`)
  line(`insert into detective_scenes(id, version_id, position, title, title_ar, image_path, introduction, introduction_ar) values ('${sid}', '${version}', ${sc.position}, ${q(en(sc.title, sc.title_ar))}, ${q(sc.title_ar)}, '${img(`scene-${sc.position}`)}', ${q(en(sc.introduction, sc.introduction_ar))}, ${q(sc.introduction_ar)}) on conflict (id) do nothing;`)
  for (const e of sc.evidence) {
    const b = boxes[e.key] ?? e
    for (const k of ['x', 'y', 'width', 'height']) if (typeof b[k] !== 'number') fail(`box ${k} missing for ${e.key}`)
    if (b.x < 0 || b.y < 0 || b.x + b.width > 100.01 || b.y + b.height > 100.01 || b.width <= 0 || b.height <= 0) fail(`box out of range for ${e.key}`)
    if (!CLASS.has(e.classification)) fail(`classification ${e.classification}`)
    const title = en(e.title, e.title_ar)
    line(`insert into detective_evidence(id, scene_id, evidence_key, internal_title, public_title, public_title_ar, x, y, width, height, public_description, public_description_ar, admin_explanation, admin_explanation_ar, classification, importance, unlock_rule) values ('${evId[e.key]}', '${sid}', ${q(e.key)}, ${q(title)}, ${q(title)}, ${q(e.title_ar)}, ${b.x}, ${b.y}, ${b.width}, ${b.height}, ${q(en(e.description, e.description_ar))}, ${q(e.description_ar)}, ${q(en(e.admin_explanation, e.admin_explanation_ar))}, ${q(e.admin_explanation_ar)}, ${q(e.classification)}, ${Math.min(5, Math.max(1, e.importance || 3))}, '{}'::jsonb) on conflict (id) do nothing;`)
  }
}

for (const [i, r] of pack.relations.entries()) {
  const t = REL[r.relation_type] ?? fail(`relation ${r.relation_type}`)
  line(`insert into detective_evidence_relations(id, version_id, from_evidence_id, to_evidence_id, relation_type, public_explanation, public_explanation_ar) values ('${uuid(`relation:${i}`)}', '${version}', '${ev(r.from, 'relation')}', '${ev(r.to, 'relation')}', ${q(t)}, ${q(en(r.public_explanation, r.public_explanation_ar))}, ${q(r.public_explanation_ar)}) on conflict (id) do nothing;`)
}

// ---- questions
const finalQ = pack.stages_questions.filter((x) => x.type === 'FINAL_CONCLUSION')
if (finalQ.length !== 1) fail('exactly one FINAL_CONCLUSION question is required')
const evByKey = Object.fromEntries(evidence.map((e) => [e.key, e]))
let finalId = null
for (const qq of pack.stages_questions) {
  const id = uuid(`question:${qq.stage}:${qq.position}`)
  if (!stageId[qq.stage]) fail(`question stage ${qq.stage}`)
  let type = qq.type, options = (qq.options ?? []).map((o) => ({ id: o.id, text: en(o.text, o.text_ar), text_ar: o.text_ar ?? o.text }))
  let key = qq.answer_key, prompt = qq.prompt, promptAr = qq.prompt_ar
  if (type === 'EVENT_ORDERING' || type === 'CHRONOLOGICAL_REASONING') {
    const order = key.order, byId = Object.fromEntries(options.map((o) => [o.id, o]))
    if (!order?.every((x) => byId[x])) fail(`ordering ${qq.position}`)
    const rot = (a, n) => a.slice(n).concat(a.slice(0, n))
    const variants = [order, [order[1], order[0], ...order.slice(2)], rot(order, 1), [...order].reverse()]
    const correctAt = pick(4, `order:${qq.stage}:${qq.position}`)
    const arranged = variants.slice(1); arranged.splice(correctAt, 0, order)
    options = arranged.map((seq, i) => ({ id: String.fromCharCode(97 + i), text: seq.map((x) => byId[x].text).join(' → '), text_ar: seq.map((x) => byId[x].text_ar).join(' ← ') }))
    key = { option_id: String.fromCharCode(97 + correctAt) }
    type = 'MULTIPLE_CHOICE'
    promptAr = `${promptAr} اختر الترتيب الصحيح.`
    if (prompt) prompt = `${prompt} Choose the correct order.`
  } else if (type === 'FIND_EVIDENCE') {
    const target = evByKey[key.evidence_key] ?? fail(`find evidence ${key.evidence_key}`)
    const same = evidence.filter((e) => e.scenePos === target.scenePos)
    options = same.map((e, i) => ({ id: String.fromCharCode(97 + i), text: en(e.title, e.title_ar), text_ar: e.title_ar }))
    key = { option_id: String.fromCharCode(97 + same.indexOf(target)) }
    type = 'MULTIPLE_CHOICE'
  } else if (type === 'EVIDENCE_RELATIONSHIP') {
    key = { from: ev(key.from, 'answer'), to: ev(key.to, 'answer'), relation: REL[key.relation] ?? fail(`answer relation ${key.relation}`) }
    options = []
  } else if (type === 'TRUE_FALSE') {
    key = { value: String(key.value) }
    options = []
  } else if (!['MULTIPLE_CHOICE', 'SUSPECT_SELECTION', 'CONTRADICTION_IDENTIFICATION', 'FINAL_CONCLUSION'].includes(type)) {
    if (!options.length || !key.option_id) fail(`unsupported question type ${type}`)
    type = 'MULTIPLE_CHOICE'
  }
  if (key.option_id && !options.some((o) => o.id === key.option_id)) fail(`answer ${key.option_id} not in options (${qq.stage} ${qq.position})`)
  const assoc = (qq.associated_evidence ?? []).map((k) => ev(k, 'question'))
  const first = evByKey[(qq.associated_evidence ?? [])[0]]
  const explAr = qq.type === 'FINAL_CONCLUSION' ? pack.solution.public_reveal_ar : (qq.explanation_ar ?? first?.admin_explanation_ar ?? null)
  const explEn = qq.type === 'FINAL_CONCLUSION' ? en(pack.solution.public_reveal, pack.solution.public_reveal_ar) : en(qq.explanation ?? first?.admin_explanation, explAr)
  if (qq.type === 'FINAL_CONCLUSION') finalId = id
  line(`insert into detective_questions(id, version_id, stage_id, question_type, prompt, prompt_ar, options, answer_key, accepted_alternatives, explanation, explanation_ar, associated_evidence, points, penalty, position) values ('${id}', '${version}', '${stageId[qq.stage]}', ${q(type)}, ${q(en(prompt, promptAr))}, ${q(promptAr)}, ${j(options)}, ${j(key)}, '[]'::jsonb, ${q(explEn)}, ${q(explAr)}, ${uarr(assoc)}, ${qq.points ?? 10}, ${qq.penalty ?? -2}, ${qq.position}) on conflict (id) do nothing;`)
}

for (const s of pack.suspects) {
  const desc = s.description_ar ?? s.background_ar ?? ''
  line(`insert into detective_suspects(id, version_id, name, name_ar, description, description_ar, relationship, background, timeline, alibi) values ('${suspectId[s.key]}', '${version}', ${q(s.name)}, ${q(s.name_ar)}, ${q(en(s.description, desc))}, ${q(desc + (s.background_ar ? ` ${s.background_ar}` : ''))}, ${q(s.relationship_ar ?? s.relationship)}, ${q(s.relationship ?? s.relationship_ar)}, ${j(s.timeline ?? {})}, ${q(s.alibi_ar ?? s.alibi)}) on conflict (id) do nothing;`)
  if (pack.pack_version >= 2) line(`update detective_suspects set motive = ${q(en(s.motive, s.motive_ar))}, motive_ar = ${q(s.motive_ar)}, alibi_ar = ${q(s.alibi_ar)}, relationship_ar = ${q(s.relationship_ar)}${s.portrait ? `, portrait_path = '${img(s.portrait)}'` : ''} where id = '${suspectId[s.key]}';`)
}
for (const [i, st] of pack.statements.entries()) {
  const sid = suspectId[st.suspect] ?? fail(`statement suspect ${st.suspect}`)
  line(`insert into detective_statements(id, suspect_id, statement, statement_ar, truth_status, conflicting_evidence, admin_explanation, admin_explanation_ar) values ('${uuid(`statement:${i}`)}', '${sid}', ${q(en(st.statement, st.statement_ar))}, ${q(st.statement_ar)}, ${q(TRUTH[st.truth_status] ?? fail(`truth ${st.truth_status}`))}, ${uarr((st.conflicting_evidence ?? []).map((k) => ev(k, 'statement')))}, ${q(en(st.admin_explanation, st.admin_explanation_ar))}, ${q(st.admin_explanation_ar)}) on conflict (id) do nothing;`)
}
for (const t of pack.timeline_events) {
  line(`insert into detective_timeline_events(id, version_id, event_key, label, label_ar, window_key, position) values ('${uuid(`timeline:${t.event_key}`)}', '${version}', ${q(t.event_key)}, ${q(en(t.label, t.label_ar))}, ${q(t.label_ar)}, ${q(t.window_key)}, ${t.position}) on conflict (id) do nothing;`)
}
for (const h of pack.hints) {
  line(`insert into detective_hints(id, version_id, stage_id, hint_text, hint_text_ar, unlock_rule, penalty, position) values ('${uuid(`hint:${h.stage}:${h.position}`)}', '${version}', '${stageId[h.stage] ?? fail(`hint stage ${h.stage}`)}', ${q(en(h.hint_text, h.hint_text_ar))}, ${q(h.hint_text_ar)}, '{}'::jsonb, ${h.penalty ?? -2}, ${h.position}) on conflict (id) do nothing;`)
  if (h.level) line(`update detective_hints set level = ${h.level} where id = '${uuid(`hint:${h.stage}:${h.position}`)}';`)
}
const S = pack.solution
const alts = (S.alternative_hypotheses ?? []).map((a) => ({ en: en(a.en, a.ar), ar: a.ar, why_wrong_en: en(a.why_wrong_en, a.why_wrong_ar), why_wrong_ar: a.why_wrong_ar }))
line(`insert into detective_solutions(id, version_id, public_reveal, public_reveal_ar, solution_key, alternative_hypotheses, educational_explanation, educational_explanation_ar) values ('${uuid('solution')}', '${version}', ${q(en(S.public_reveal, S.public_reveal_ar))}, ${q(S.public_reveal_ar)}, ${j({ final_question: finalId })}, ${j(alts)}, ${q(en(S.educational_explanation, S.educational_explanation_ar))}, ${q(S.educational_explanation_ar)}) on conflict (id) do nothing;`)
for (const [i, p] of pack.lab_procedures.entries()) {
  line(`insert into detective_lab_procedures(id, version_id, procedure_key, evidence_id, exam_type, title, title_ar, requires_evidence, result, result_ar, report, release_seconds, points, position) values ('${uuid(`lab:${p.key}`)}', '${version}', ${q(p.key)}, ${p.evidence ? `'${ev(p.evidence, 'lab')}'` : 'null'}, ${q(p.exam_type)}, ${q(en(p.title, p.title_ar))}, ${q(p.title_ar)}, ${uarr((p.requires ?? []).map((k) => ev(k, 'lab')))}, ${q(en(p.result, p.result_ar))}, ${q(p.result_ar)}, ${j(p.report ?? {})}, ${p.release_seconds ?? 0}, ${p.points ?? 0}, ${p.position ?? i + 1}) on conflict (id) do nothing;`)
}
for (const c of pack.confrontations) {
  line(`insert into detective_confrontations(id, version_id, suspect_id, evidence_id, response, response_ar, reveals_contradiction, points) values ('${uuid(`confront:${c.suspect}:${c.evidence}`)}', '${version}', '${suspectId[c.suspect] ?? fail(`confront suspect ${c.suspect}`)}', '${ev(c.evidence, 'confrontation')}', ${q(en(c.response, c.response_ar))}, ${q(c.response_ar)}, ${c.reveals_contradiction ? 'true' : 'false'}, ${c.points ?? 0}) on conflict (id) do nothing;`)
}
if (pack.verdict) {
  const V = pack.verdict
  const opts = (xs) => xs.map((o) => ({ id: o.id, text: en(o.text, o.text_ar), text_ar: o.text_ar }))
  line(`insert into detective_verdict_criteria(version_id, suspect_id, motive_options, motive_answer, method_options, method_answer, key_evidence, timeline_order${V.weights ? ', weights' : ''}) values ('${version}', '${suspectId[V.suspect]}', ${j(opts(V.motives))}, ${q(V.motive)}, ${j(opts(V.methods))}, ${q(V.method)}, ${uarr(V.key_evidence.map((k) => ev(k, 'verdict')))}, ${V.timeline?.length ? `array[${V.timeline.map(q).join(',')}]::text[]` : `'{}'::text[]`}${V.weights ? `, ${j(V.weights)}` : ''}) on conflict (version_id) do nothing;`)
}
line(`end $$;`)
console.log(out.join('\n'))
console.error(`${slug}: ${pack.scenes.length} scenes, ${evidence.length} evidence, ${pack.stages_questions.length} questions, ${pack.suspects.length} suspects -> case ${caseId}`)
